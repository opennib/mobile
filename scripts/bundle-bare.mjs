#!/usr/bin/env node
// Bundle the opennib Bare worker for shipping into the RN app.
// Mirrors what `npx qvac bundle sdk` does for the SDK's internal worker:
// resolves the entry's dep graph, emits a single self-contained bundle
// that RNBK loads via `Worklet.start(filename, bundle)`.
//
// The bundle is emitted as BINARY and wrapped in a base64 `module.exports`
// so Metro ships one plain-ASCII string literal. The Hermes side decodes it
// back to bytes before `Worklet.start` (which accepts a TypedArray). Passing
// the bundle as a raw JS string corrupted it once it contained non-ASCII
// module sources — byte offsets in the bundle header vs. UTF-16 code units
// in the string disagree somewhere between Metro and the native bridge, and
// the worklet then failed with "SyntaxError: Unexpected end of input".
// Bytes are bytes; base64 survives every layer unchanged.
import { existsSync, readFileSync, unlinkSync, writeFileSync } from "node:fs"
import { spawnSync } from "node:child_process"
import { createRequire } from "node:module"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const here = dirname(fileURLToPath(import.meta.url))
const pkg = resolve(here, "..")
const entry = resolve(pkg, "bare/index.mjs")
const binaryOut = resolve(pkg, "bare/worker.bundle.tmp")
const out = resolve(pkg, "bare/worker.bundle.cjs")
// The worker imports @qvac/sdk (Bare-direct), whose dependency graph uses
// Node-style specifiers ("process", "fs", …) that only resolve under Bare
// through the SDK's global import overrides — the same map `npx qvac bundle
// sdk` uses when building the SDK's own worker bundle.
// The SDK's exports map doesn't expose package.json, so resolve its main
// entry and walk up to the package root.
const require = createRequire(import.meta.url)
let sdkRoot = dirname(require.resolve("@qvac/sdk"))
while (!existsSync(resolve(sdkRoot, "package.json")) || !sdkRoot.endsWith("sdk")) {
  const parent = dirname(sdkRoot)
  if (parent === sdkRoot) throw new Error("cannot locate @qvac/sdk package root")
  sdkRoot = parent
}
const sdkImports = resolve(sdkRoot, "bare-imports.json")

// Run bare-pack's CLI under this Node directly: resolving it by module path
// avoids depending on a shell wrapper around npx and on where npm chose to
// place the package.
const barePackBin = resolve(dirname(require.resolve("bare-pack/package")), "bin.js")

const result = spawnSync(
  process.execPath,
  [
    barePackBin,
    entry,
    "--out",
    binaryOut,
    "--format",
    "bundle",
    "--linked",
    "--imports",
    sdkImports,
    "--host",
    "ios-arm64",
    "--host",
    "ios-arm64-simulator",
    "--host",
    "android-arm64",
  ],
  { stdio: "inherit", cwd: pkg },
)

if (result.error) {
  console.error(result.error)
  process.exit(1)
}
if (result.status !== 0) {
  process.exit(result.status ?? 1)
}

const bytes = readFileSync(binaryOut)
unlinkSync(binaryOut)
writeFileSync(
  out,
  `// Generated by scripts/bundle-bare.mjs — do not edit.\n` +
    `// Base64 of the binary bare-pack bundle; decoded to bytes in\n` +
    `// src/native/bare-worker.ts before Worklet.start.\n` +
    `module.exports = "${bytes.toString("base64")}"\n`,
)

console.log(`bundled → ${out} (${bytes.length} bytes binary, base64-wrapped)`)
